import fs from 'node:fs';
import path from 'node:path';

const SRC = 'C:\\Users\\user\\OneDrive\\Desktop\\FamHeritage\\design\\assets\\fonts';
const OUT = 'C:\\Users\\user\\OneDrive\\Desktop\\FamHeritage\\design\\assets\\css\\fonts.css';

const faces = [
  { family: 'Fraunces', file: 'Fraunces-normal-latin.woff2', weight: '300 700', style: 'normal' },
  { family: 'Newsreader', file: 'Newsreader-normal-latin.woff2', weight: '300 600', style: 'normal' },
  { family: 'Instrument Serif', file: 'InstrumentSerif-normal-latin.woff2', weight: '400', style: 'normal' },
  { family: 'Instrument Serif', file: 'InstrumentSerif-italic-latin.woff2', weight: '400', style: 'italic' },
  { family: 'Inter', file: 'Inter-normal-latin.woff2', weight: '300 700', style: 'normal' },
  { family: 'Instrument Sans', file: 'InstrumentSans-normal-latin.woff2', weight: '400 700', style: 'normal' },
];

fs.mkdirSync(path.dirname(OUT), { recursive: true });

const blocks = faces.map((f) => {
  const p = path.join(SRC, f.file);
  if (!fs.existsSync(p)) throw new Error('missing font ' + p);
  const b64 = fs.readFileSync(p).toString('base64');
  return `@font-face{\n  font-family:'${f.family}';\n  font-style:${f.style};\n  font-weight:${f.weight};\n  font-display:block;\n  src:url(data:font/woff2;base64,${b64}) format('woff2');\n}`;
});

const header = `/* Generated by tools/build-fonts.mjs - do not edit by hand.\n   Fonts are embedded as base64 so the prototype works from file:// with no network. */\n\n`;
fs.writeFileSync(OUT, header + blocks.join('\n\n') + '\n', 'utf8');
console.log('wrote', OUT, (fs.statSync(OUT).size / 1024).toFixed(0) + 'KB');
